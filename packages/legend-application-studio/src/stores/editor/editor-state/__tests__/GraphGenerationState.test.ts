import { test, expect, beforeEach, afterEach, jest } from '@jest/globals';
import { flowResult } from 'mobx';
import type { GeneratorFn } from '@finos/legend-shared';
import { unitTest } from '@finos/legend-shared/test';
import { TEST__buildGraphWithEntities } from '@finos/legend-graph/test';
import type { Entity } from '@finos/legend-storage';
import { TEST__getTestEditorStore } from '../../__test-utils__/EditorStoreTestUtils.js';
import type { EditorStore } from '../../EditorStore.js';
import { TEST_DATA__GenerationSpecificationStages } from './TEST_DATA__GenerationSpecificationStages.js';

const buildClassEntity = (path: string): Entity => {
  const separatorIndex = path.lastIndexOf('::');
  return {
    path,
    content: {
      _type: 'class',
      name: path.substring(separatorIndex + 2),
      package: path.substring(0, separatorIndex),
      properties: [],
    },
    classifierPath: 'meta::pure::metamodel::type::Class',
  };
};

let editorStore: EditorStore;
let updateGenerationGraph: jest.Mock;

/**
 * Stage 1 is `test::tMapping` and `test::tMapping2`, stage 2 is `test::tMapping3`.
 */
const mockEngine = (generatedPaths: Record<string, string[]>): void => {
  const graphManager = editorStore.graphManagerState.graphManager;
  jest
    .spyOn(graphManager, 'generateModel')
    .mockImplementation(async (element) =>
      (generatedPaths[element.path] ?? []).map(buildClassEntity),
    );
  // rebuild the generation model the way the application does, without the UI bits
  // NOTE: the flow is typed as a generator function but called as one returning a promise
  updateGenerationGraph = jest.fn(async () => {
    const graph = editorStore.graphManagerState.graph;
    graph.generationModel = graphManager.createGenerationModel();
    await graphManager.buildGenerations(
      graph,
      editorStore.graphState.graphGenerationState.generatedEntities,
      editorStore.graphManagerState.generationsBuildState,
    );
  });
  jest
    .spyOn(editorStore.graphState, 'updateGenerationGraphAndApplication')
    .mockImplementation(
      updateGenerationGraph as unknown as () => GeneratorFn<void>,
    );
};

const generateModels = async (): Promise<Error | undefined> =>
  flowResult(editorStore.graphState.graphGenerationState.generateModels());

const getGeneratedPaths = (): string[] =>
  editorStore.graphManagerState.graph.generationModel.allOwnElements.map(
    (element) => element.path,
  );

beforeEach(async () => {
  editorStore = TEST__getTestEditorStore();
  await TEST__buildGraphWithEntities(
    editorStore.graphManagerState,
    TEST_DATA__GenerationSpecificationStages as Entity[],
  );
});

afterEach(() => {
  jest.restoreAllMocks();
});

test(
  unitTest(
    'Generation fails before updating the graph when a generated element is already in the project',
  ),
  async () => {
    mockEngine({
      'test::tMapping': ['model::serialized::Trade', 'test::tMapping3'],
    });

    const error = await generateModels();

    expect(error?.message).toBe(
      `Can't generate models: failure occured at stage 1 with specification 'test::tMapping'. Error: Generated element 'test::tMapping3' already exists in the project`,
    );
    expect(updateGenerationGraph).not.toHaveBeenCalled();
    expect(getGeneratedPaths()).toEqual([]);
    expect(
      editorStore.graphState.graphGenerationState.modelGenerationFailures.map(
        (failure) => failure.elementRef.value.path,
      ),
    ).toEqual(['test::tMapping']);
  },
);

test(
  unitTest(
    'Generation fails before updating the graph when a generated element was generated by an earlier stage',
  ),
  async () => {
    mockEngine({
      'test::tMapping': ['model::serialized::CounterParty'],
      'test::tMapping3': [
        'model::target::Promotion',
        'model::serialized::CounterParty',
      ],
    });

    const error = await generateModels();

    expect(error?.message).toBe(
      `Can't generate models: failure occured at stage 2 with specification 'test::tMapping3'. Error: Generated element 'model::serialized::CounterParty' was already generated by 'test::tMapping'`,
    );
    // only stage 1 made it to the graph
    expect(updateGenerationGraph).toHaveBeenCalledTimes(1);
    expect(getGeneratedPaths()).toEqual(['model::serialized::CounterParty']);
  },
);

test(
  unitTest(
    'Generation updates the graph when generated elements are not duplicated',
  ),
  async () => {
    mockEngine({
      'test::tMapping': ['model::serialized::CounterParty'],
      'test::tMapping3': ['model::target::Promotion'],
    });

    const error = await generateModels();

    expect(error).toBeUndefined();
    expect(updateGenerationGraph).toHaveBeenCalledTimes(2);
    expect(getGeneratedPaths().sort()).toEqual([
      'model::serialized::CounterParty',
      'model::target::Promotion',
    ]);
  },
);
